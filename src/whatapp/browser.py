"""Presentation helpers, with no GTK dependency and no discovery of their own."""

import os
from pathlib import Path

from .cli import search_reasons
from .inventory import classify


CATEGORIES = (("all", "All launchers"), ("eligible", "Menu applications"),
              ("excluded", "Excluded"), ("shadowed", "Shadowed"), ("uncertain", "Uncertain"))

# Fields whose null value means "this key is absent from the file or environment",
# which is a definite fact, not a failure to determine something.
NOT_SET_FIELDS = frozenset({"Display name", "Raw Exec command", "Icon name or path",
                            "OnlyShowIn", "NotShowIn", "TryExec", "Current desktops"})

FOOTER = ("Generated by WhatApp, a read-only desktop launcher inspector. "
          "A launcher is not necessarily the application; dpkg ownership does not establish "
          "how it was installed. Nothing was changed.")


def filter_launchers(entries, category="all", query=""):
    query = query.strip()
    return [entry for entry in entries
            if (category == "all" or classify(entry)[category])
            and (not query or search_reasons(entry, query)[0])]


def origin(entry, env=None):
    env = os.environ if env is None else env
    home = Path(env.get("HOME") or Path.home())
    data_home = Path(env.get("XDG_DATA_HOME") or home / ".local/share")
    if not data_home.is_absolute():
        data_home = home / ".local/share"
    path = Path(entry["desktop_entry_path"])
    return "User-level" if path.is_relative_to(data_home / "applications") or path.is_relative_to(home) else "System-level"


def text(value):
    if value is None:
        return "Unknown"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, list):
        return "\n".join(map(str, value)) if value else "None"
    return str(value)


def ownership_text(entry, path):
    """Distinguish 'dpkg says nobody owns it' from 'could not ask dpkg'."""
    if path is None:
        return "Unknown (no resolved executable to look up)"
    if any(note == f"No exact dpkg ownership identified for {path}." for note in entry["notes"]):
        return "None found"
    return "Unknown"


def inspector_rows(entry):
    """(title, rendered text) for every inspector field, with unambiguous null values.

    'Unknown' is reserved for things WhatApp could not determine. Keys that are simply
    absent render as '(not set)', an empty dpkg answer as 'None found', and list values
    as one '- ' item per line so they cannot be mistaken for multi-line scalars.
    """
    rows = []
    for title, value in inspector_fields(entry):
        if value is None:
            if title in NOT_SET_FIELDS:
                rendered = "(not set)"
            elif title == "Launcher package owner (dpkg)":
                rendered = ownership_text(entry, entry["desktop_entry_path"])
            elif title == "Executable package owner (dpkg)":
                rendered = ownership_text(entry, entry["executable_path"])
            else:
                rendered = "Unknown"
        elif isinstance(value, list):
            rendered = "\n".join(f"- {item}" for item in value) if value else "None"
        else:
            rendered = text(value)
        rows.append((title, rendered))
    return rows


def inspector_title(entry):
    return f"WhatApp inspector: {entry['desktop_entry_id'] or entry['desktop_entry_path']}"


def inspector_text(entry):
    """The whole inspector as plain text: what Copy All and select-all produce.

    Self-describing on purpose, since this text is typically pasted into a bug
    report or an AI chat without the rest of the window.
    """
    body = "\n\n".join(f"{title}\n{rendered}" for title, rendered in inspector_rows(entry))
    return f"{inspector_title(entry)}\n\n{body}\n\n{FOOTER}"


def inspector_fields(entry):
    visibility, precedence = entry["visibility"], entry["precedence"]
    return [
        ("Display name", entry["display_name"]),
        ("Desktop-entry ID", entry["desktop_entry_id"]),
        ("Location", origin(entry)),
        ("Launcher file path", entry["desktop_entry_path"]),
        ("Raw Exec command", entry["exec"]),
        ("Resolved executable path", entry["executable_path"]),
        ("Icon name or path", entry["icon"]),
        ("Launcher package owner (dpkg)", entry["package_ownership"]["desktop_entry"]),
        ("Executable package owner (dpkg)", entry["package_ownership"]["executable"]),
        ("Original installation method", entry["installation_method"]),
        ("Visibility", visibility["status"]),
        ("Visibility reasons", visibility["reasons"]),
        ("Precedence", precedence["status"]),
        ("Preferred launcher path", precedence["preferred_path"]),
        ("Precedence candidates", precedence["candidate_paths"]),
        ("Hidden", visibility["hidden"]),
        ("NoDisplay", visibility["no_display"]),
        ("OnlyShowIn", visibility["only_show_in"]),
        ("NotShowIn", visibility["not_show_in"]),
        ("Current desktops", visibility["current_desktops"]),
        ("TryExec", visibility["try_exec"]["value"]),
        ("TryExec status", visibility["try_exec"]["status"]),
        ("Notes", entry["notes"]),
        ("Issues", entry["issues"]),
    ]
